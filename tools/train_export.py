#!/usr/bin/env python3
"""Train the 5 -> 8 -> 2 rover MLP offline and export source/weights.h.

Behaviour cloning of a simple reactive expert. Swap `expert()` / the dataset for
logged teleop data (Nunchuk runs) or an RL policy if you want something smarter.

    pip install numpy scikit-learn
    python tools/train_export.py            # writes ../source/weights.h

Conventions (must match firmware):
  * inputs  : normalized ray distance, order -45, -22.5, 0, 22.5, 45 deg (1 = clear)
  * outputs : [left, right] wheel command in [-1, 1]; firmware applies tanh to the
              output layer, so we regress atanh(target) with a linear output here.
  * layout  : W1[H][IN], W2[OUT][H] (row-major, i.e. sklearn coefs transposed)
"""
import os
import numpy as np
from sklearn.neural_network import MLPRegressor

IN, H, OUT = 5, 8, 2
rng = np.random.default_rng(0)


def expert(s):
    """s: (N,5) -> (N,2) wheel commands. +angle = left, so s[:,3:5] are left sensors."""
    r = (s[:, 0] + s[:, 1]) / 2
    l = (s[:, 3] + s[:, 4]) / 2
    f = s[:, 2]
    fwd = 0.9 * np.clip((f - 0.15) / 0.5, -0.4, 1.0)
    turn = 1.4 * (r - l)                                  # + = turn right (left wheel faster)
    side = np.where(r >= l, 1.0, -1.0)                    # escape toward clearer side
    turn += 0.8 * side * (1.0 - np.clip(f / 0.5, 0.0, 1.0))
    left = np.clip(fwd + turn, -0.95, 0.95)
    right = np.clip(fwd - turn, -0.95, 0.95)
    return np.stack([left, right], axis=1)


def make_dataset(n=40000):
    s = rng.uniform(0.05, 1.0, size=(n, IN))
    s[rng.random((n, IN)) < 0.45] = 1.0                   # many "clear" rays
    # smooth some samples (walls tend to occlude neighbouring rays together)
    k = rng.random(n) < 0.4
    s[k] = np.clip(0.5 * s[k] + 0.5 * s[k].mean(axis=1, keepdims=True), 0.05, 1.0)
    return s.astype(np.float32)


def fmt_array(a, indent="    "):
    if a.ndim == 1:
        return "{ " + ", ".join(f"{v:.6f}f" for v in a) + " }"
    rows = [indent + "{ " + ", ".join(f"{v: .6f}f" for v in row) + " }," for row in a]
    return "{\n" + "\n".join(rows) + "\n}"


def main():
    X = make_dataset()
    Y = expert(X)
    Yp = np.arctanh(Y)                                    # pre-activation targets

    net = MLPRegressor(hidden_layer_sizes=(H,), activation="tanh", solver="adam",
                       learning_rate_init=3e-3, max_iter=600, random_state=0)
    net.fit(X, Yp)

    pred = np.tanh(net.predict(X))
    print(f"MSE (post-tanh): {np.mean((pred - Y) ** 2):.5f}")

    W1 = net.coefs_[0].T.astype(np.float32)               # (H, IN)
    B1 = net.intercepts_[0].astype(np.float32)            # (H,)
    W2 = net.coefs_[1].T.astype(np.float32)               # (OUT, H)
    B2 = net.intercepts_[1].astype(np.float32)            # (OUT,)

    out = os.path.join(os.path.dirname(__file__), "..", "source", "weights.h")
    with open(out, "w") as f:
        f.write("// weights.h - generated by tools/train_export.py. DO NOT EDIT.\n")
        f.write("#pragma once\n\nnamespace weights {\n\n")
        f.write(f"constexpr int N_IN  = {IN};\nconstexpr int N_HID = {H};\nconstexpr int N_OUT = {OUT};\n\n")
        f.write(f"static const float W1[N_HID][N_IN] = {fmt_array(W1)};\n\n")
        f.write(f"static const float B1[N_HID] = {fmt_array(B1)};\n\n")
        f.write(f"static const float W2[N_OUT][N_HID] = {fmt_array(W2)};\n\n")
        f.write(f"static const float B2[N_OUT] = {fmt_array(B2)};\n\n")
        f.write("} // namespace weights\n")
    print("wrote", os.path.normpath(out))


# --- PyTorch users: export the same layout -------------------------------------
